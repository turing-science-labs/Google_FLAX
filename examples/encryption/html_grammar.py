import random
class HTMLGrammar:
    def __init__(self):
        self.rules = {
            "S": [["html_open", "HEAD", "BODY", "html_close"]],
            "HEAD": [["head_open", "TITLE", "head_close"]],
            "TITLE": [["title_open", "text", "title_close"]],
            "BODY": [["body_open", "ELEMENTS", "body_close"]],
            "ELEMENTS": [["ELEMENT", "ELEMENTS"], ["ELEMENT"]],
            "ELEMENT": [["BLOCK_ELEMENT"], ["INLINE_ELEMENT"]],
            "BLOCK_ELEMENT": [
                ["div_open", "ELEMENTS", "div_close"],
                ["p_open", "TEXT_NODES", "p_close"],
                ["h1_open", "text", "h1_close"],
                ["h2_open", "text", "h2_close"],
                ["ul_open", "LIST_ITEMS", "ul_close"]
            ],
            "INLINE_ELEMENT": [
                ["span_open", "text", "span_close"],
                ["a_open", "text", "a_close"],
                ["strong_open", "text", "strong_close"],
                ["em_open", "text", "em_close"]
            ],
            "LIST_ITEMS": [
                ["li_open", "text", "li_close", "LIST_ITEMS"],
                ["li_open", "text", "li_close"]
            ],
            "TEXT_NODES": [["text", "TEXT_NODES"], ["text"]]
        }
        self.terminals = {
            "html_open": "<html>\n", "html_close": "</html>",
            "head_open": "<head>\n", "head_close": "</head>\n",
            "title_open": "  <title>", "title_close": "</title>\n",
            "body_open": "<body>\n", "body_close": "</body>\n",
            "div_open": "  <div>\n", "div_close": "  </div>\n",
            "p_open": "  <p>", "p_close": "</p>\n",
            "h1_open": "  <h1>", "h1_close": "</h1>\n",
            "h2_open": "  <h2>", "h2_close": "</h2>\n",
            "ul_open": "  <ul>\n", "ul_close": "  </ul>\n",
            "li_open": "    <li>", "li_close": "</li>\n",
            "span_open": "<span>", "span_close": "</span>",
            "strong_open": "<strong>", "strong_close": "</strong>",
            "em_open": "<em>", "em_close": "</em>"
        }
        self.text_choices = [
            "Web Design", "Hello World", "AI Research", "Colab Notebook",
            "Python Power", "Data Science", "Grammar Rule", "Artificial Intelligence",
            "Machine Learning", "Deep Learning", "Neural Network", "Big Data",
            "Cloud Computing", "Cyber Security", "Software Engineering", "Algorithm"
        ]
        self.href_choices = [
            "https://google.com", "https://github.com", "https://wikipedia.org",
            "https://python.org", "https://colab.research.google.com"
        ]
    def generate_symbol(self, symbol, depth=0):
        if depth > 10:
            if symbol in ["ELEMENTS", "LIST_ITEMS", "TEXT_NODES"]:
                return self.generate_symbol(self.rules[symbol][-1][-1], depth + 1)
            if symbol == "ELEMENT":
                return self.generate_symbol("INLINE_ELEMENT", depth + 1)
        if symbol in self.terminals:
            return self.terminals[symbol]
        if symbol == "text":
            return random.choice(self.text_choices)
        if symbol == "a_open":
            return f'<a href="{random.choice(self.href_choices)}">'
        if symbol in self.rules:
            production = random.choice(self.rules[symbol])
            return "".join(self.generate_symbol(s, depth + 1) for s in production)
        return ""
    def generate_html(self) -> str:
        return self.generate_symbol("S")

html_gen = HTMLGrammar()
sample_html = html_gen.generate_html()
print("=== Sample Generated HTML ===")
print(sample_html)

unique_scripts = set()
target_unique = 100001
print(f"\nGenerating up to {target_unique} unique scripts...")

while len(unique_scripts) < target_unique:
    unique_scripts.add(html_gen.generate_html())
    if len(unique_scripts) % 25000 == 0:
        print(f"Progress: Collected {len(unique_scripts)} unique scripts so far...")

print(f"\nSuccess! Verified {len(unique_scripts)} distinct HTML documents generated by the grammar.")
